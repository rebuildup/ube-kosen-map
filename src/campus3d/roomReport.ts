/**
 * Machine-readable room extraction report (Issue #72 acceptance evidence).
 *
 * For every registry building and floor this records what the floor-plan
 * partition produced: source SVG groups, polygon/face counts, hole counts,
 * calibrated dimensions, partition statistics, and — where extraction
 * could not run — the reason. Dimensions derive from the calibrated
 * drawing scale (GEO.metersPerUnit = 0.84 m/unit); they are estimates,
 * never survey measurements (docs/campus3d-provenance.md).
 *
 * Pure data: no THREE, no DOM. The committed JSON snapshot lives at
 * quality/room-report.json and is regenerated by
 * `bun run quality/room-report.mts`.
 */

import { CAMPUS_MODEL_DATA } from "./data/campusModelData";
import { withComplementedBuildings } from "./data/complemented";
import { HP_BUILDING_INFO } from "./data/buildingRegistry";
import { CAMPUS3D_TO_MAP2D } from "./data/map2dBuildings";
import { BUILDING_FLOOR_CONFIGS } from "../data/floorConfig";
import { METERS_PER_DRAWING_UNIT } from "./geo/drawingTransform";
import { buildCampusModel, type BuildingModel } from "./geo/buildings";
import type { RoomSpec } from "./geo/buildings";

export const ROOM_REPORT_SCHEMA = "ube-kosen-map/room-report@1" as const;

/** Round to 6 decimals so the committed JSON is stable across JS runtimes. */
const r6 = (x: number): number => {
  const v = Math.round(x * 1e6) / 1e6;
  return Object.is(v, -0) ? 0 : v;
};

export type RoomReportFloorStatus =
  | "partitioned"
  | "single-face"
  | "no-linework"
  | "massing"
  | "nodata"
  | "missing-data";

export interface RoomReportRoom {
  readonly id: string;
  readonly floor: number;
  readonly kind: RoomSpec["kind"];
  readonly label: string;
  readonly areaM2: number;
  readonly widthM: number;
  readonly depthM: number;
  readonly perimeterM: number;
  readonly faceCount: number;
  readonly holeCount: number;
  readonly vertexCount: number;
  /** Always "calibrated-estimate": dims come from the 0.84 m/unit calibration. */
  readonly accuracy: "calibrated-estimate";
}

export interface RoomReportFloor {
  readonly building: string;
  readonly buildingName: string;
  readonly floor: number;
  /** SVG group ids in public/campus-map3.svg this floor derives from. */
  readonly sourceSvgGroups: readonly string[];
  readonly status: RoomReportFloorStatus;
  /** Why no rooms were produced (empty when status === "partitioned"). */
  readonly reason: string;
  readonly plateAreaM2: number | null;
  readonly faceAreaM2: number | null;
  readonly areaDeltaRatio: number | null;
  readonly wallSegments: number | null;
  readonly stairSegments: number | null;
  readonly faces: number | null;
  readonly slivers: number | null;
  readonly orphanHoles: number | null;
  readonly rooms: readonly RoomReportRoom[];
}

export interface RoomReportBuilding {
  readonly key: string;
  readonly name: string;
  readonly category: string;
  readonly status: BuildingModel["status"];
  /** Published footprint from the school HP data (cross-check only). */
  readonly footprintM2: number | null;
  /** Largest floor plate area in m^2 (calibrated estimate). */
  readonly maxPlateAreaM2: number | null;
  /** maxPlateAreaM2 / footprintM2; ~1.0 means the calibration is consistent. */
  readonly footprintRatio: number | null;
}

export interface RoomReport {
  readonly schema: typeof ROOM_REPORT_SCHEMA;
  readonly scale: {
    readonly metersPerDrawingUnit: number;
    readonly basis: "calibrated";
    readonly measured: false;
  };
  readonly summary: {
    readonly buildings: number;
    readonly floors: number;
    readonly floorsWithRooms: number;
    readonly totalRooms: number;
    readonly massingOnly: readonly string[];
  };
  readonly buildings: readonly RoomReportBuilding[];
  readonly floors: readonly RoomReportFloor[];
}

/* ---------- source SVG group resolution ---------- */

const svgGroupsFor = (key: string, floor: number): readonly string[] => {
  const ids = CAMPUS3D_TO_MAP2D[key] ?? [];
  const groups: string[] = [];
  for (const id of ids) {
    const cfg = BUILDING_FLOOR_CONFIGS.find((b) => b.id === id);
    if (!cfg) continue;
    const fl = cfg.floors.find((f) => f.id === `${floor}F`);
    if (fl) groups.push(fl.svgGroupId);
    else if (cfg.floors.length === 0 && cfg.svgGroupId) {
      groups.push(cfg.svgGroupId);
    }
  }
  return groups;
};

/* ---------- report construction ---------- */

const roomEntry = (r: RoomSpec): RoomReportRoom => ({
  id: r.id,
  floor: r.floor,
  kind: r.kind,
  label: r.label,
  areaM2: r6(r.areaM2),
  widthM: r6(r.widthM),
  depthM: r6(r.depthM),
  perimeterM: r6(r.perimeterM),
  faceCount: r.faces.length,
  holeCount: r.faces.reduce((a, f) => a + f.holes.length, 0),
  vertexCount: r.faces.reduce(
    (a, f) => a + f.outer.length + f.holes.reduce((h, x) => h + x.length, 0),
    0,
  ),
  accuracy: "calibrated-estimate",
});

const floorStatus = (
  b: BuildingModel,
  floor: number,
): { status: RoomReportFloorStatus; reason: string } => {
  if (b.status === "nodata") {
    return { status: "nodata", reason: "no source data for this building" };
  }
  if (b.status === "missing-data") {
    return {
      status: "missing-data",
      reason: "building key has no entry in the public dataset",
    };
  }
  const rep = b.floorReports.find((r) => r.floor === floor);
  if (!rep) {
    const isDorm = b.category.startsWith("寮");
    return {
      status: "massing",
      reason: isDorm
        ? "dormitory interior is restricted data; exterior massing only"
        : "no public interior floor plan for this floor",
    };
  }
  const { stats } = rep;
  if (stats.faces === 0) {
    return {
      status: "no-linework",
      reason: "floor plate has no usable wall linework",
    };
  }
  if (stats.faces === 1) {
    return {
      status: "single-face",
      reason:
        "wall linework does not close any room; the floor is one open face",
    };
  }
  return { status: "partitioned", reason: "" };
};

export const buildRoomReport = (data = CAMPUS_MODEL_DATA): RoomReport => {
  const scene = withComplementedBuildings(data);
  const model = buildCampusModel(scene);
  const floors: RoomReportFloor[] = [];
  const buildings: RoomReportBuilding[] = [];

  for (const b of model.buildings) {
    const hp = HP_BUILDING_INFO[b.key];
    const floorPlates = b.floorReports.map((r) => r.stats.plateAreaU2);
    const maxPlateU2 = floorPlates.length ? Math.max(...floorPlates) : null;
    const maxPlateM2 =
      maxPlateU2 === null
        ? null
        : r6(maxPlateU2 * METERS_PER_DRAWING_UNIT ** 2);
    buildings.push({
      key: b.key,
      name: b.name,
      category: b.category,
      status: b.status,
      footprintM2: hp?.footprintM2 ?? null,
      maxPlateAreaM2: maxPlateM2,
      footprintRatio: hp && maxPlateM2 ? r6(maxPlateM2 / hp.footprintM2) : null,
    });

    if (b.status !== "ok") {
      floors.push({
        building: b.key,
        buildingName: b.name,
        floor: 0,
        sourceSvgGroups: svgGroupsFor(b.key, 0),
        status: b.status,
        reason:
          b.status === "nodata"
            ? "no source data for this building"
            : "building key has no entry in the public dataset",
        plateAreaM2: null,
        faceAreaM2: null,
        areaDeltaRatio: null,
        wallSegments: null,
        stairSegments: null,
        faces: null,
        slivers: null,
        orphanHoles: null,
        rooms: [],
      });
      continue;
    }

    const repByFloor = new Map(b.floorReports.map((r) => [r.floor, r]));
    const roomFloors = [...new Set(b.rooms.map((r) => r.floor))].sort(
      (a, c) => a - c,
    );
    const allFloors = [
      ...new Set([...b.floorNumbers, ...roomFloors, ...repByFloor.keys()]),
    ].sort((a, c) => a - c);

    for (const n of allFloors) {
      const { status, reason } = floorStatus(b, n);
      const rep = repByFloor.get(n);
      const rooms = b.rooms
        .filter((r) => r.floor === n)
        .sort((a, c) => a.id.localeCompare(c.id))
        .map(roomEntry);
      floors.push({
        building: b.key,
        buildingName: b.name,
        floor: n,
        sourceSvgGroups: svgGroupsFor(b.key, n),
        status,
        reason,
        plateAreaM2: rep
          ? r6(rep.stats.plateAreaU2 * METERS_PER_DRAWING_UNIT ** 2)
          : null,
        faceAreaM2: rep
          ? r6(rep.stats.faceAreaU2 * METERS_PER_DRAWING_UNIT ** 2)
          : null,
        areaDeltaRatio: rep ? r6(rep.stats.areaDeltaRatio) : null,
        wallSegments: rep ? rep.stats.wallSegments : null,
        stairSegments: rep ? rep.stats.stairSegments : null,
        faces: rep ? rep.stats.faces : null,
        slivers: rep ? rep.stats.slivers : null,
        orphanHoles: rep ? rep.stats.orphanHoles : null,
        rooms,
      });
    }
  }

  return {
    schema: ROOM_REPORT_SCHEMA,
    scale: {
      metersPerDrawingUnit: METERS_PER_DRAWING_UNIT,
      basis: "calibrated",
      measured: false,
    },
    summary: {
      buildings: buildings.length,
      floors: floors.length,
      floorsWithRooms: floors.filter((f) => f.rooms.length > 0).length,
      totalRooms: floors.reduce((a, f) => a + f.rooms.length, 0),
      massingOnly: buildings
        .filter(
          (b) =>
            b.status === "ok" &&
            !floors.some((f) => f.building === b.key && f.rooms.length > 0),
        )
        .map((b) => b.key),
    },
    buildings,
    floors,
  };
};
